package com.allowance.manager.core.domain.model

import java.time.LocalDate

/**
 * 급여 지급일 보정에 쓰는 비영업일(공휴일·은행 휴무일) 집합.
 *
 * 지급일이 주말이면 [BudgetCycle.adjustToBusinessDay]가 요일로 판정해 당길 수 있지만, 공휴일은
 * 설날·추석처럼 매년 날짜가 바뀌어 코드로 계산할 수 없다. 그래서 Remote Config(`kr_holidays`)로
 * 내려주고, 값을 못 받았을 때만 [FALLBACK]을 쓴다.
 *
 * ⚠️ [FALLBACK]은 오프라인·최초 실행 대비용 안전망이다. 정확한 값은 Remote Config로 관리한다.
 * 근로자의 날(5/1)은 법정공휴일이 아니지만 은행이 쉬어 급여가 앞당겨 지급되므로 포함한다.
 */
object KrHolidays {

    /**
     * Remote Config 문자열 → 날짜 집합.
     * JSON 배열(`["2026-01-01","2026-02-17"]`)과 콤마 목록(`2026-01-01,2026-02-17`) 둘 다 받는다.
     * 형식이 깨진 토큰은 조용히 버린다 — 원격 값 오타 하나로 사이클이 망가지면 안 된다.
     */
    fun parse(raw: String): Set<LocalDate> =
        raw.split(',')
            .mapNotNull { token ->
                runCatching { LocalDate.parse(token.trim().trim('[', ']', '"', ' ')) }.getOrNull()
            }
            .toSet()

    /** Remote Config 미수신 시 사용할 기본 공휴일(2026~2027). */
    val FALLBACK: Set<LocalDate> = setOf(
        // 2026
        "2026-01-01",                               // 신정
        "2026-02-16", "2026-02-17", "2026-02-18",   // 설날 연휴
        "2026-03-02",                               // 삼일절 대체공휴일(3/1 일요일)
        "2026-05-01",                               // 근로자의 날 (은행 휴무)
        "2026-05-05",                               // 어린이날
        "2026-05-25",                               // 부처님오신날 대체공휴일(5/24 일요일)
        "2026-06-03",                               // 전국동시지방선거
        "2026-08-17",                               // 광복절 대체공휴일(8/15 토요일)
        "2026-09-24", "2026-09-25", "2026-09-28",   // 추석 연휴 + 대체공휴일(9/26 토요일)
        "2026-10-05",                               // 개천절 대체공휴일(10/3 토요일)
        "2026-10-09",                               // 한글날
        "2026-12-25",                               // 성탄절
        // 2027
        "2027-01-01",                               // 신정
        "2027-02-05", "2027-02-08", "2027-02-09",   // 설날 연휴(2/6 토·2/7 일) + 대체공휴일
        "2027-03-01",                               // 삼일절
        "2027-05-05",                               // 어린이날
        "2027-05-13",                               // 부처님오신날
        "2027-08-16",                               // 광복절 대체공휴일(8/15 일요일)
        "2027-09-14", "2027-09-15", "2027-09-16",   // 추석 연휴
        "2027-10-04",                               // 개천절 대체공휴일(10/3 일요일)
        "2027-10-11",                               // 한글날 대체공휴일(10/9 토요일)
        "2027-12-27",                               // 성탄절 대체공휴일(12/25 토요일)
    ).map(LocalDate::parse).toSet()
}
